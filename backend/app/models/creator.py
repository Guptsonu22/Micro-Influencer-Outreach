"""Pydantic data models for Creator profiles, metrics, classification, and outreach."""

from datetime import datetime
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class CreatorMetrics(BaseModel):
    """Source-backed metrics for a YouTube channel."""
    subscriber_count: Optional[int] = Field(
        default=None,
        description="Public subscriber count from YouTube API. None if hidden by creator."
    )
    is_subscriber_count_hidden: bool = Field(
        default=False,
        description="True if subscriber count is explicitly hidden by channel."
    )
    video_count: Optional[int] = Field(
        default=None,
        description="Total public video uploads from YouTube API."
    )
    view_count: Optional[int] = Field(
        default=None,
        description="Lifetime cumulative channel views."
    )
    recent_video_sample_size: int = Field(
        default=0,
        description="Number of recent videos sampled to estimate engagement rate."
    )
    avg_recent_views: Optional[float] = Field(
        default=None,
        description="Average views across the sampled recent videos. None if no videos."
    )
    avg_recent_likes: Optional[float] = Field(
        default=None,
        description="Average likes across the sampled recent videos."
    )
    avg_recent_comments: Optional[float] = Field(
        default=None,
        description="Average comments across the sampled recent videos."
    )
    estimated_engagement_rate: Optional[float] = Field(
        default=None,
        description="Calculated engagement rate percentage. None if insufficient data."
    )
    engagement_formula_used: Optional[str] = Field(
        default="((avg_likes + avg_comments) / avg_views) * 100",
        description="Explicit formula documentation for how engagement rate was calculated."
    )
    metric_timestamp: datetime = Field(
        default_factory=datetime.utcnow,
        description="UTC timestamp when metrics were fetched."
    )


class EnrichmentData(BaseModel):
    """Enriched creator details including public contact email and content themes."""
    contact_email: str = Field(
        default="Not Found",
        description="Publicly verified email. MUST be 'Not Found' if not explicitly located."
    )
    social_links: Dict[str, str] = Field(
        default_factory=dict,
        description="Links to Instagram, X/Twitter, Website, etc. extracted from public bio/links."
    )
    content_themes: List[str] = Field(
        default_factory=list,
        description="Keywords and topics representing creator's core content niche."
    )
    recent_video_titles: List[str] = Field(
        default_factory=list,
        description="Sample of real recent video titles published by creator."
    )
    enriched_at: Optional[datetime] = Field(
        default=None,
        description="Timestamp when enrichment was performed."
    )
    enrichment_source: str = Field(
        default="YouTube Channel Snippet & Recent Uploads",
        description="Source provenance for enriched data."
    )


class ClassificationResult(BaseModel):
    """Qualification and brand-fit decision with granular reasons."""
    is_qualified: bool = Field(
        default=False,
        description="Whether the creator meets all brand-fit filter criteria."
    )
    fit_score: int = Field(
        default=0,
        ge=0,
        le=100,
        description="Calculated fit score between 0 and 100 based on rules."
    )
    niche: str = Field(
        default="Unknown",
        description="Determined content niche (e.g., Tech & AI, EdTech, Coding Tutorials)."
    )
    reasons: List[str] = Field(
        default_factory=list,
        description="Transparent breakdown of why creator qualified or was rejected."
    )
    evaluated_at: datetime = Field(
        default_factory=datetime.utcnow,
        description="Timestamp when classification evaluation ran."
    )


class OutreachMessage(BaseModel):
    """Personalized outreach copy and delivery tracking state."""
    email_subject: Optional[str] = Field(
        default=None,
        description="Personalized email subject line mentioning creator work."
    )
    email_body: Optional[str] = Field(
        default=None,
        description="Personalized email pitch with explicit collaboration angles."
    )
    instagram_dm: Optional[str] = Field(
        default=None,
        description="Concise, platform-appropriate Instagram DM draft."
    )
    generated_at: Optional[datetime] = Field(
        default=None,
        description="Timestamp when copy was generated by AI."
    )
    status: str = Field(
        default="draft",
        description="One of: 'draft', 'approved', 'simulated', 'sent', 'failed'."
    )
    approval_timestamp: Optional[datetime] = Field(
        default=None,
        description="Timestamp when human operator approved the message."
    )
    delivery_timestamp: Optional[datetime] = Field(
        default=None,
        description="Timestamp when simulation or approved email dispatch occurred."
    )
    is_simulation: bool = Field(
        default=True,
        description="True if message was only simulated without real external delivery."
    )
    error_message: Optional[str] = Field(
        default=None,
        description="Error details if delivery attempt failed."
    )


class CreatorRecord(BaseModel):
    """Complete, self-contained record for an influencer."""
    channel_id: str = Field(
        ...,
        description="Unique YouTube Channel ID (e.g., UCxxxxxxxx)."
    )
    title: str = Field(
        ...,
        description="Official YouTube channel display title."
    )
    custom_url: Optional[str] = Field(
        default="Unavailable",
        description="Custom handle or vanity URL (e.g., @coder_dev)."
    )
    channel_url: str = Field(
        ...,
        description="Direct URL to channel page (https://www.youtube.com/channel/...)."
    )
    description: str = Field(
        default="",
        description="Public channel description / bio."
    )
    published_at: Optional[str] = Field(
        default="Unknown",
        description="Channel creation date from API."
    )
    country: Optional[str] = Field(
        default="Unknown",
        description="Channel country code from snippet."
    )
    thumbnail_url: Optional[str] = Field(
        default=None,
        description="Profile avatar image URL."
    )

    # Sub-models
    metrics: CreatorMetrics = Field(default_factory=CreatorMetrics)
    enrichment: EnrichmentData = Field(default_factory=EnrichmentData)
    classification: ClassificationResult = Field(default_factory=ClassificationResult)
    outreach: OutreachMessage = Field(default_factory=OutreachMessage)

    # Provenance and Integrity Metadata
    is_synthetic: bool = Field(
        default=False,
        description="CRITICAL: True ONLY if generated as a demo record. Real API records MUST be False."
    )
    source_api: str = Field(
        default="YouTube Data API v3",
        description="Data provenance source."
    )
    retrieved_at: datetime = Field(
        default_factory=datetime.utcnow,
        description="Timestamp when channel record was initially discovered."
    )
    updated_at: datetime = Field(
        default_factory=datetime.utcnow,
        description="Timestamp of last update."
    )
